/**
 * Writes src/data/lastmod.json: the last git commit date (YYYY-MM-DD) of every
 * source file whose content feeds a sitemap <lastmod> (state + city data files,
 * the top-level page sources, the program pages, the hub pages).
 *
 * RUN LOCALLY BEFORE EVERY COMMIT THAT TOUCHES THOSE FILES:
 *   node scripts/lastmod-manifest.mjs && git add src/data/lastmod.json
 * Vercel builds from a shallow clone with no history, so the build cannot
 * compute these dates itself; scripts/build-sitemaps.mjs reads this manifest.
 *
 * A file with uncommitted changes gets today's date (it is about to be
 * committed). A file git has never seen gets null, and the sitemap then omits
 * lastmod for its URLs rather than inventing one. Learn and scenario pages are
 * not in here: their lastmod comes from MDX frontmatter.
 */
import { execFileSync } from 'node:child_process';
import { readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const git = (...args) => execFileSync('git', args, { cwd: root, encoding: 'utf8' }).trim();
const astroFiles = (dir) =>
  readdirSync(join(root, dir))
    .filter((f) => f.endsWith('.astro'))
    .map((f) => `${dir}/${f}`);

const files = [
  'src/data/states.json',
  ...readdirSync(join(root, 'src/data/cities'))
    .filter((f) => f.endsWith('.json'))
    .map((f) => `src/data/cities/${f}`),
  ...astroFiles('src/pages'),
  ...astroFiles('src/pages/programs'),
  'src/pages/states/index.astro',
  'src/pages/learn/index.astro',
  'src/pages/dscr-loans/index.astro',
].sort();

// Local calendar date, the same day git's %cs will record for the commit.
const now = new Date();
const today = new Date(now.getTime() - now.getTimezoneOffset() * 60000).toISOString().slice(0, 10);
const manifest = {};
let dirtyCount = 0;
for (const f of files) {
  const dirty = git('status', '--porcelain', '--', f) !== '';
  const committed = git('log', '-1', '--format=%cs', '--', f);
  if (dirty) dirtyCount++;
  manifest[f] = dirty ? today : committed || null;
}

const out = {
  _note:
    'Generated by scripts/lastmod-manifest.mjs (git commit date per file, YYYY-MM-DD). Regenerate before committing content changes; never hand-edit.',
  generated: today,
  files: manifest,
};
writeFileSync(join(root, 'src/data/lastmod.json'), JSON.stringify(out, null, 2) + '\n');
console.log(
  `[lastmod-manifest] ${files.length} files recorded (${dirtyCount} uncommitted, dated ${today}) -> src/data/lastmod.json`,
);
